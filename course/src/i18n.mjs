export function translate(language, key) {
  if (language !== 'en' || typeof key !== 'string') return key;
  if (english[key]) return english[key];
  const slow = /^訊息傳送太快，請稍候 (\d+) 秒。$/.exec(key);
  if (slow) return `Message sent too soon. Please wait ${slow[1]} seconds.`;
  const cooldown = /^語音留言傳送太快，請稍候 (\d+) 秒。$/.exec(key);
  if (cooldown) return `Voice message sent too soon. Please wait ${cooldown[1]} seconds.`;
  const invalidText = /^(訊息|暱稱|限制詞|檢舉原因|語音留言)需為 1–(\d+) 個字，不能包含控制字元。$/.exec(key);
  if (invalidText) return `${{ 訊息: 'Message', 暱稱: 'Nickname', 限制詞: 'Blocked word', 檢舉原因: 'Report reason', 語音留言: 'Voice message' }[invalidText[1]]} must be 1–${invalidText[2]} characters without control characters.`;
  const voiceCost = /^語音留言需花費 (\d+) 示範點數。$/.exec(key);
  if (voiceCost) return `A voice message costs ${voiceCost[1]} demo points.`;
  return key;
}
export function preferredLanguage(storage) {
  try { return storage?.getItem('group9-language') === 'en' ? 'en' : 'zh'; }
  catch { return 'zh'; }
}
